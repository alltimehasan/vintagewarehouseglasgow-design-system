/* Colour */
{
  const names = themes.map((t) => t.name);
  const cards = tokens.color.tokens.map((t) => {
    const chips = themes.map((th) => {
      const v = themeValue(t, th.id);
      const hex = colorHex(t.name, th.id);
      return `<span style="background:${hex}; color:${lum(hex) > 0.4 ? '#131313' : '#f6f5f2'}">${th.name}</span>`;
    }).join('');
    const rows = themes.map((th) => `<dt>${th.name}</dt><dd>${esc(themeValue(t, th.id))}</dd>`).join('');
    return `<div class="sg-swatch" id="${t.name}"><div class="sg-chips">${chips}</div><div class="sg-swatch-body"><h3>${t.name}</h3><dl>${rows}</dl><p>${esc(t.usage || '')}</p></div></div>`;
  }).join('\n');

  const PAIRS = [
    ['ink', 'surface', 4.5], ['ink', 'surface-raised', 4.5], ['ink-muted', 'surface', 4.5], ['ink-muted', 'surface-raised', 4.5],
    ['on-band', 'band', 4.5], ['on-band-muted', 'band', 4.5], ['brick', 'surface', 4.5], ['brick', 'surface-raised', 4.5],
    ['brick', 'brick-soft', 4.5], ['on-brick', 'brick', 4.5], ['blue', 'surface', 4.5], ['blue', 'blue-soft', 4.5],
    ['stock', 'surface', 4.5], ['stock', 'stock-soft', 4.5], ['danger', 'surface', 4.5], ['danger', 'danger-soft', 4.5],
    ['brick', 'band', 4.5], ['ink-muted', 'band', 4.5], ['line-strong', 'surface', 3], ['line-strong', 'surface-raised', 3],
  ];
  const rows = PAIRS.map(([fg, bg, need]) => {
    const cells = themes.map((th) => {
      const r = contrast(colorHex(fg, th.id), colorHex(bg, th.id));
      return `<td class="num ${r >= need ? 'sg-pass' : 'sg-fail'}">${r.toFixed(2)}${r >= need ? '' : ' ✕'}</td>`;
    }).join('');
    return `<tr><td><code>${fg}</code> on <code>${bg}</code></td><td class="num">${need}:1</td>${cells}</tr>`;
  }).join('\n');
  const legibility = `
<section class="sg-prose" id="legibility">
<h2>Legibility</h2>
<p>WCAG contrast for the pairs the usage notes allow, in each theme. Text needs 4.5:1; borders and marks that carry meaning need 3:1. The two pairs that fail in the light theme are the reason brick and muted text are never set on the black band there.</p>
<div class="sg-table-wrap"><table class="sg-table"><thead><tr><th>Pair</th><th class="num">Needs</th>${names.map((n) => `<th class="num">${n}</th>`).join('')}</tr></thead><tbody>${rows}</tbody></table></div>
</section>`;
  write(path.join(ROOT, 'colour.html'), page({
    file: 'colour.html', title: 'Colour', eyebrow: 'Foundations',
    intro: `${tokens.color.tokens.length} tokens in ${themes.length} themes. Black and off-white from the logo and the painted panel, one brick accent from the wall, the container blue for New stock.`,
    body: `<div class="sg-swatches">${cards}</div>${legibility}`,
  }));
}

/* Type */
