#!/usr/bin/env node
'use strict';
/*
  Builds the Vintage Warehouse Glasgow style guide.
  Source of truth: project/ (tokens.json, README.md, components/, assets/, fonts/), the same files the
  Claude design-system artifact holds. Output, all static, no dependencies:
    dist/      tokens.css (generated), vwg.css, vwg.js, fonts/, images/   <- drop these into the website build
    previews/  one standalone page per component, used in the iframes
    *.html     the style guide pages
  Run: node build.js
*/
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SRC = path.join(ROOT, 'project');
const DIST = path.join(ROOT, 'dist');
const PREVIEWS = path.join(ROOT, 'previews');

const read = (p) => fs.readFileSync(path.join(SRC, p), 'utf8');
const exists = (p) => fs.existsSync(path.join(SRC, p));
const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
const copy = (from, to) => { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(from, to); };
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const tokens = JSON.parse(read('tokens.json'));
const index = JSON.parse(read('design-system.json'));
const TITLE = index.title;
const BUILT = new Date().toISOString().slice(0, 10);

/* ---------- 1. dist: assets, fonts, the two bundles, the generated tokens.css ---------- */
fs.rmSync(DIST, { recursive: true, force: true });
fs.rmSync(PREVIEWS, { recursive: true, force: true });

const blobToFile = {};
const assetGroups = index.groups.map((name) => index.assetGroups[name]);
for (const group of assetGroups) {
  for (const name of group.order) {
    const f = group.files[name];
    blobToFile[f.blob] = `dist/images/${f.name}`;
    copy(path.join(SRC, 'assets', group.name, f.name), path.join(DIST, 'images', f.name));
  }
}
for (const f of tokens.type.fonts) copy(path.join(SRC, f.file), path.join(DIST, 'fonts', path.basename(f.file)));
copy(path.join(SRC, 'components/bundle.css'), path.join(DIST, 'vwg.css'));
copy(path.join(SRC, 'components/bundle.js'), path.join(DIST, 'vwg.js'));
const relBlobs = (html, prefix) => html.replace(/\/_blob\/([0-9a-f]{32})/g, (m, id) => (blobToFile[id] ? prefix + blobToFile[id] : m));

const themes = tokens.color.themes;
const FIRST = themes[0].id;
const isAlias = (v) => typeof v === 'string' && /^\{[\w.-]+\}$/.test(v);
const themeValue = (t, id) => (typeof t.value === 'string' ? t.value : (t.value[id] ?? t.value[FIRST]));
const cssValue = (v) => (isAlias(v) ? `var(--${v.slice(1, -1)})` : v);
const colorHex = (name, id) => {               // resolved hex for contrast maths
  const t = tokens.color.tokens.find((x) => x.name === name);
  if (!t) return null;
  const v = themeValue(t, id);
  return isAlias(v) ? colorHex(v.slice(1, -1), id) : v;
};

function tokensCss() {
  const L = [`/* ${TITLE} — generated from project/tokens.json by build.js. Edit tokens.json and rebuild; do not edit this file. */`];
  for (const f of tokens.type.fonts) {
    L.push(`@font-face { font-family: "${f.family}"; src: url("fonts/${path.basename(f.file)}") format("woff2"); font-weight: ${f.weight}; font-style: ${f.style || 'normal'}; font-display: swap; }`);
  }
  const block = (id) => [
    ...tokens.color.tokens.map((t) => `  --${t.name}: ${cssValue(themeValue(t, id))};`),
    ...((tokens.shadow && tokens.shadow.tokens) || []).map((t) => `  --${t.name}: ${cssValue(themeValue(t, id))};`),
    `  color-scheme: ${id};`,
  ];
  L.push(`:root, [data-theme="${FIRST}"] {`, ...block(FIRST), `}`);
  for (const th of themes.slice(1)) {
    L.push(`[data-theme="${th.id}"] {`, ...block(th.id), `}`);
    if (th.id === 'dark') L.push(`@media (prefers-color-scheme: dark) {`, `  :root:not([data-theme="${FIRST}"]) {`, ...block(th.id).map((l) => '  ' + l), `  }`, `}`);
  }
  L.push(`:root {`);
  for (const t of tokens.spacing.tokens) L.push(`  --${t.name}: ${t.value};`);
  for (const t of tokens.radius.tokens) L.push(`  --${t.name}: ${t.value};`);
  for (const [k, v] of Object.entries(tokens.type.families)) L.push(`  --font-${k}: ${v};`);
  L.push(`}`);
  for (const g of tokens.type.groups) {
    for (const s of g.styles) {
      const d = [`font-family: var(--font-${s.family || g.family})`, `font-size: ${s.fontSize}`];
      if (s.lineHeight) d.push(`line-height: ${s.lineHeight}`);
      if (s.fontWeight) d.push(`font-weight: ${s.fontWeight}`);
      if (s.letterSpacing && s.letterSpacing !== '0') d.push(`letter-spacing: ${s.letterSpacing}`);
      if (s.fontStyle) d.push(`font-style: ${s.fontStyle}`);
      L.push(`.${s.name} { ${d.join('; ')}; }`);
    }
  }
  return L.join('\n') + '\n';
}
write(path.join(DIST, 'tokens.css'), tokensCss());

/* ---------- 2. a small markdown renderer for the brand book and guidelines ---------- */
function inline(s) {
  return s.split('`').map((part, i) => (i % 2
    ? `<code>${esc(part)}</code>`
    : esc(part).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>').replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>'))).join('');
}
function md(text) {
  const out = [];
  let para = [], list = null, code = null, lang = '';
  const flushPara = () => { if (para.length) { out.push(`<p>${inline(para.join(' '))}</p>`); para = []; } };
  const flushList = () => { if (list) { out.push(`<ul>${list.map((i) => `<li>${inline(i)}</li>`).join('')}</ul>`); list = null; } };
  for (const raw of text.split('\n')) {
    const line = raw.replace(/\s+$/, '');
    if (code !== null) {
      if (line.startsWith('```')) { out.push(`<pre><code class="language-${lang}">${esc(code.join('\n'))}</code></pre>`); code = null; } else code.push(raw);
      continue;
    }
    if (line.startsWith('```')) { flushPara(); flushList(); code = []; lang = line.slice(3).trim() || 'text'; continue; }
    const h = /^(#{1,4}) (.*)$/.exec(line);
    if (h) { flushPara(); flushList(); out.push(`<h${h[1].length} id="${slug(h[2])}">${inline(h[2])}</h${h[1].length}>`); continue; }
    const li = /^- (.*)$/.exec(line);
    if (li) { flushPara(); (list = list || []).push(li[1]); continue; }
    if (!line.trim()) { flushPara(); flushList(); continue; }
    if (list) { list[list.length - 1] += ' ' + line.trim(); continue; }
    para.push(line.trim());
  }
  flushPara(); flushList();
  return out.join('\n');
}

/* ---------- 3. previews: the artifact's preview documents, made standalone ---------- */
const THEME_SYNC = `(function(){var d=document.documentElement;function set(t){if(t==='light'||t==='dark')d.setAttribute('data-theme',t);else d.removeAttribute('data-theme')}var q=new URLSearchParams(location.search).get('theme');if(q)set(q);addEventListener('message',function(e){var m=e.data;if(m&&m.type==='vwg-theme')set(m.theme)});function size(){if(parent!==window)parent.postMessage({type:'vwg-size',height:d.scrollHeight},'*')}addEventListener('load',function(){if(parent!==window)parent.postMessage({type:'vwg-ready'},'*');size();if(window.ResizeObserver)new ResizeObserver(size).observe(document.body)})})();`;

function parseMarker(html) {
  const lines = html.split('\n');
  const marker = {};
  if (lines[0].startsWith('<!-- @dsCard')) {
    for (const m of lines.shift().matchAll(/(\w+)=("([^"]*)"|(\S+))/g)) marker[m[1]] = m[3] !== undefined ? m[3] : m[4];
  }
  return { marker, doc: lines.join('\n') };
}
function buildPreview(name) {
  const { marker, doc } = parseMarker(read(`components/${name}/preview.html`));
  const head = `\n<link rel="stylesheet" href="../dist/tokens.css">\n<link rel="stylesheet" href="../dist/vwg.css">\n<script src="../dist/vwg.js"></script>\n<script>${THEME_SYNC}</script>`;
  let page = relBlobs(doc, '../');
  page = /<meta charset="utf-8">/i.test(page) ? page.replace(/<meta charset="utf-8">/i, (m) => m + head) : page.replace(/<head>/i, (m) => m + head);
  write(path.join(PREVIEWS, `${name}.html`), page);
  const body = /<body[^>]*>([\s\S]*?)<\/body>/i.exec(doc);
  const source = body ? relBlobs(body[1], '').replace(/^\n+|\n+$/g, '') : '';
  return { marker, source };
}

