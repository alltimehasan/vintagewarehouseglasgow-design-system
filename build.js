/* Components */
{
  const bundle = read('components/bundle.js');
  const header = /@ds-bundle:\s*(\{.*?\})\s*\*\//.exec(bundle);
  const order = header ? JSON.parse(header[1]).components.map((c) => c.name) : [];
  for (const d of fs.readdirSync(path.join(SRC, 'components'), { withFileTypes: true })) {
    if (d.isDirectory() && d.name !== 'Cover' && d.name !== 'lib' && d.name !== 'src' && !order.includes(d.name) && exists(`components/${d.name}/preview.html`)) order.push(d.name);
  }
  const sections = [];
  const toc = [];
  for (const name of order) {
    if (!exists(`components/${name}/preview.html`)) continue;
    const { marker, source } = buildPreview(name);
    const guide = exists(`components/${name}/README.md`) ? md(read(`components/${name}/README.md`)) : '';
    const w = +marker.width || 960;
    const h = +marker.height || 120;
    toc.push(`<a href="#${slug(name)}">${name}</a>`);
    sections.push(`
<section class="sg-component" id="${slug(name)}">
<header><span class="sg-eyebrow">${esc(marker.group || 'Component')}</span><h2>${esc(name)}</h2></header>
${preview(`previews/${name}.html`, `${name} preview`, w, h, 'loading="lazy"')}
<div class="sg-preview-bar"><span>Live preview, ${w}px layout, follows the theme switch.</span><a class="sg-open" href="previews/${name}.html" target="_blank" rel="noopener">Open in a new tab</a></div>
<div class="sg-prose">${guide}</div>
<details><summary>Preview markup</summary><pre><code class="language-html">${esc(source)}</code></pre></details>
</section>`);
  }
  write(path.join(ROOT, 'components.html'), page({
    file: 'components.html', title: 'Components', eyebrow: 'Build',
    intro: `${sections.length} patterns the website is built from, each with its live preview, guidelines and markup. Styles are in dist/vwg.css with the prefix vwg-; small ones also have builders in dist/vwg.js as window.VWG.`,
    body: `<nav class="sg-toc" aria-label="Components">${toc.join('')}</nav>${sections.join('\n')}`,
  }));
}

